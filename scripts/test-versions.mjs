import { makeFixture, makeSuite, runPb, pbJson, readJournal, BASE_ENV } from './test-fixture-playbook.mjs';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const s = makeSuite('versions');
const root = s.track(makeFixture({ loops: 'active: null\nloops: []\n' }));
const run = args => runPb(root, args);
const noWrite = (label, args, pattern) => {
  const before = readFileSync(join(root, 'memory/journal.ndjson'), 'utf8');
  const r = run(args);
  s.ok(label, r.code !== 0 && pattern.test(r.combined), r.combined);
  s.ok(`${label}: no row`, readFileSync(join(root, 'memory/journal.ndjson'), 'utf8') === before);
};
const answerBrief = () => {
  const file = join(root, 'memory/cycle.md');
  writeFileSync(file, readFileSync(file, 'utf8').replace(/\(Your host memory is the PAST[\s\S]*?memory\.\)/, 'None. Folder memory wins.'));
};
noWrite('V5 stop must be executable', ['version', 'new', '--name', 'v1', '--goal', 'one'], /stop-check/);
const created = run(['version', 'new', '--name', 'v1', '--title', 'First version', '--goal', 'one', '--stop-check', 'node -e "process.exit(0)"']);
s.ok('new opens a named version', created.code === 0, created.combined);
if (created.code !== 0) s.finish();
answerBrief();
let versions = pbJson(root, ['version', 'list', '--json']).versions;
const first = versions.find(v => v.version === 'v1');
s.ok('version reuses loop fields', first?.state === 'open' && first.goal === 'one' && first.stop_checks.length === 1 && first.title === 'First version');
noWrite('V1 only one open version', ['version', 'new', '--name', 'v2', '--goal', 'two', '--stop-check', 'node -v'], /V1/);
const planned = run(['plan', '--goal', 'feature', '--kind', 'feature', '--check', 'node -v']);
const task = /Planned \[([^\]]+)\]/.exec(planned.out)?.[1];
s.ok('V2 feature is born in active version', planned.code === 0 && !!task, planned.combined);
if (!task) s.finish();
const shown = pbJson(root, ['task', 'show', task, '--json']).task;
s.ok('birth stamp: version, kind, loop', shown.version === 'v1' && shown.kind === 'feature' && shown.loop_id === first.id);
noWrite('V4 follow-up cannot override parent version', ['plan', '--goal', 'wrong version', '--dep', task, '--version', 'v2', '--check', 'node -v'], /V4/);
noWrite('V6 close cannot abandon open tasks', ['version', 'close'], /V6/);
s.ok('freeze succeeds', run(['version', 'freeze']).code === 0);
noWrite('V3 frozen refuses features', ['plan', '--goal', 'new feature', '--kind', 'feature', '--check', 'node -v'], /V3/);
const fix = run(['plan', '--goal', 'fix', '--kind', 'fix', '--check', 'node -v']);
const fixId = /Planned \[([^\]]+)\]/.exec(fix.out)?.[1];
s.ok('frozen accepts fixes', fix.code === 0 && !!fixId, fix.combined);
noWrite('carry requires an explicit next draft', ['version', 'carry', task, '--to', 'next'], /draft/);
const draft = run(['version', 'new', '--draft', '--name', 'v2', '--goal', 'two', '--stop-check', 'node -v']);
s.ok('next draft can be staged without opening another version', draft.code === 0, draft.combined);
const draftValid = run(['validate']);
s.ok('pb validate passes while a draft version is staged (plan-20261011-006)', draftValid.code === 0 && !/invalid status: draft/.test(draftValid.combined), draftValid.combined.slice(-600));
const beforeCarry = readJournal(root).length;
s.ok('explicit carry succeeds', run(['version', 'carry', task, '--to', 'next']).code === 0);
const carryRows = readJournal(root).slice(beforeCarry);
s.ok('carry writes source and destination rows', carryRows.length === 2 && carryRows.every(r => r.action === 'carry') && new Set(carryRows.map(r => r.loop_id)).size === 2);
s.ok('carry rows have unique monotonic sequence numbers', carryRows[1].seq === carryRows[0].seq + 1);
noWrite('drop needs a reason', ['version', 'drop', fixId], /reason/);
s.ok('explicit drop succeeds', run(['version', 'drop', fixId, '--reason', 'Superseded']).code === 0);
s.ok('V6 verified close succeeds after every open card disposed', run(['version', 'close']).code === 0);
noWrite('V2 no open version refuses planning', ['plan', '--goal', 'outside', '--check', 'node -v'], /V2/);
noWrite('V8 no open version refuses autonomous run', ['loop', 'run', '--auto'], /V8/);
noWrite('V7 closed task cannot be recorded', ['record', '--task', fixId, '--action', 'execute', '--status', 'done', '--notes', 'wrong'], /V7/);
noWrite('V7 record cannot masquerade as a comment to change closed state', ['record', '--task', fixId, '--action', 'comment', '--status', 'done', '--notes', 'wrong'], /V7/);
noWrite('V7 closed task cannot create a worker', ['worker', 'create', fixId], /V7/);
noWrite('V7 closed task cannot attach a document', ['attach', '--task', fixId, '--path', 'SKILL.md'], /V7/);
noWrite('V7 closed cycle cannot be edited', ['cycle', '--edit', '--stop', 'bypass'], /V7/);
const openNext = run(['version', 'open', '--name', 'v2']);
s.ok('staged next version opens', openNext.code === 0, openNext.combined);
answerBrief();
const carried = pbJson(root, ['task', 'show', task, '--json']).task;
s.ok('carried card keeps identity and history', carried.id === task && carried.version === 'v2' && carried.carried_from === 'v1');
const follow = run(['plan', '--goal', 'carried follow-up', '--dep', task, '--kind', 'fix', '--check', 'node -v']);
const followId = /Planned \[([^\]]+)\]/.exec(follow.out)?.[1];
s.ok('V4 follow-up inherits its open parent', follow.code === 0 && pbJson(root, ['task', 'show', followId, '--json']).task.version === 'v2');
if (followId) s.ok('dispose follow-up explicitly', run(['version', 'drop', followId, '--reason', 'Fixture only']).code === 0);
noWrite('V4 comment cannot change parent version', ['comment', '--task', task, '--text', 'wrong', '--version', 'v1'], /V4/);
s.ok('comment remains allowed on closed version', run(['comment', '--task', fixId, '--text', 'Historical context']).code === 0);
s.ok('closed-card conversation inherits its own loop', readJournal(root).at(-1).loop_id === first.id);
s.ok('past snapshot retains carried-out cards', pbJson(root, ['version', 'list', '--json']).versions.find(v => v.version === 'v1').task_snapshot.some(t => t.id === task && t.carried_to === 'v2'));
s.ok('carry state rebuild is clean', run(['repair-state', '--check']).code === 0);
s.ok('version schema validates', run(['validate']).code === 0);
const agentClose = runPb(root, ['version', 'close'], { env: { PB_RUNTIME: 'codex' } });
s.ok('agent shell cannot close a version', agentClose.code !== 0 && /person/.test(agentClose.combined));
const finish = run(['record', '--task', task, '--action', 'execute', '--status', 'done', '--notes', 'verified']);
s.ok('carried task completes under its own checks', finish.code === 0, finish.combined);
s.ok('v2 closes with executable proof', run(['version', 'close']).code === 0);
versions = pbJson(root, ['version', 'list', '--json']).versions;
s.ok('history holds both closed versions and real stop results', versions.length === 2 && versions.every(v => v.state === 'closed' && v.stop_result?.outcome === 'passed'));
noWrite('V1 names are unique', ['version', 'new', '--name', 'v1', '--goal', 'repeat', '--stop-check', 'node -v'], /already/);

const red = s.track(makeFixture({ loops: 'active: null\nloops: []\n' }));
const redNew = runPb(red, ['version', 'new', '--name', 'red', '--goal', 'red', '--stop-check', 'node -e "process.exit(1)"']);
s.ok('red stop version opens', redNew.code === 0);
const refusedClose = runPb(red, ['version', 'close']);
s.ok('V6 red stop prevents close', refusedClose.code !== 0 && /V6/.test(refusedClose.combined));
s.ok('red stop remains open', pbJson(red, ['version', 'list', '--json']).versions[0].state === 'open');
const duplicate = runPb(red, ['version', 'new', '--name', 'draft1', '--draft', '--goal', 'next', '--stop-check', 'node -v']);
s.ok('staging another draft preserves active version', duplicate.code === 0 && pbJson(red, ['version', 'list', '--json']).versions.find(v => v.version === 'red').state === 'open');
const legacy = s.track(makeFixture());
s.ok('plain playbook remains compatible', runPb(legacy, ['plan', '--goal', 'legacy', '--check', 'node -v']).code === 0);
const races = spawnSync(process.execPath, ['scripts/test-version-races.mjs'], { encoding: 'utf8', env: BASE_ENV });
console.log(races.stdout || '');
s.ok('V6/V7 permission checks hold at transaction commit', races.status === 0, races.stderr);
s.finish();

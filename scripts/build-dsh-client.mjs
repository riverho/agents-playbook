#!/usr/bin/env node
// ============================================================================
//  build-dsh-client.mjs — compile the Flow room into the DSH Client plugin bundle.
// ----------------------------------------------------------------------------
//  Output: dsh-plugin/client.js, in the format a shipped DSH client uses:
//
//      window.__ModuleLoader__.load({
//        id: "dsh-agents-playbook",
//        factory: (require) => { …CommonJS body…; return module.exports; },
//      });
//
//  That shape was read out of a real packaged client (@deepseek-ai/dsh-client-ui-layout
//  /lib/client.js), not guessed: the factory body is plain CJS and the browser module table
//  is reached by name through `require`, with react AND react/jsx-runtime supplied by the
//  host (so React is never bundled twice).
//
//  Staleness-aware, like scripts/build-app.mjs: `prepack` calls it, and a release must not
//  ship a client built from older sources — nor rebuild on every pack for no reason.
//
//  STDOUT DISCIPLINE: this runs inside `npm pack` via prepack, and stdout belongs to the
//  pack result. Every human line goes to stderr.
//
//  Usage: node scripts/build-dsh-client.mjs [--force]
// ============================================================================

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const log = (...parts) => console.error(...parts);
const SELF = fileURLToPath(import.meta.url);
const ROOT = resolve(dirname(SELF), '..');
const APP = join(ROOT, 'apps', 'flow-room');
const SCRATCH = join(APP, '.dsh-build');
const OUT = join(ROOT, 'dsh-plugin', 'client.js');
const force = process.argv.includes('--force');

const SKIP_DIRS = new Set(['node_modules', 'dist', '.dsh-build']);

function newestSource(dir) {
  let newest = 0;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const p = join(dir, entry.name);
    if (entry.isDirectory()) newest = Math.max(newest, newestSource(p));
    else newest = Math.max(newest, statSync(p).mtimeMs);
  }
  return newest;
}

const built = existsSync(OUT) ? statSync(OUT).mtimeMs : 0;
const source = Math.max(
  newestSource(join(APP, 'src')),
  ...[join(APP, 'vite.dsh.config.ts'), join(APP, 'package.json'), SELF].map((f) =>
    existsSync(f) ? statSync(f).mtimeMs : 0
  )
);

if (!force && built && built > source) {
  log('dsh client is up to date (sources older)');
  process.exit(0);
}

const vite = join(APP, 'node_modules', 'vite', 'bin', 'vite.js');
if (!existsSync(vite)) {
  log(`cannot build the DSH client: no app toolchain at ${vite}`);
  log('  cd apps/flow-room && npm install');
  process.exit(1);
}

log('building the DSH client bundle...');
const run = execFileSync(process.execPath, [vite, 'build', '--config', join(APP, 'vite.dsh.config.ts')], {
  cwd: APP,
  encoding: 'utf8',
});
if (run.stdout) process.stderr.write(run.stdout);
if (run.stderr) process.stderr.write(run.stderr);

const cjsPath = join(SCRATCH, 'client.cjs');
if (!existsSync(cjsPath)) {
  log(`the vite build produced no ${cjsPath}`);
  process.exit(1);
}
const cjs = readFileSync(cjsPath, 'utf8');
const id = JSON.parse(readFileSync(join(ROOT, 'dsh-plugin', 'package.json'), 'utf8')).name;

const indent = (text) => text.split('\n').map((line) => (line ? `\t\t${line}` : line)).join('\n');
const bundle = `// GENERATED by scripts/build-dsh-client.mjs — do not edit.
// Source: apps/flow-room/src/dsh/client.ts. Rebuild: npm run build:client
// Format: window.__ModuleLoader__.load({ id, factory(require) }) — the shape a shipped DSH
// client bundle uses. react / react/jsx-runtime come from the browser module table.
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(id)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${indent(cjs)}
\t\treturn module.exports;
\t},
});
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, bundle, 'utf8');
rmSync(SCRATCH, { recursive: true, force: true });
log(`dsh client → ${OUT} (${Math.round(bundle.length / 1024)} KB, id ${id})`);
